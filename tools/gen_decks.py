CUSTOM = re.compile(r"^([+-]?\d+)\|(.+)$")   # "-2|소환 시 …" 형태의 1회성 효과


def kw_resolve(keys, cost=3, hp=1, atk=0):
    """키워드 목록 → (배수, 가감, 표시문). 배수 먼저·가감 나중 규칙.

    ⚠ 표에 **None 이 두 종류** 있다.
       · 가감이 None (밀물·성장·흡혈·폭발) → 코스트 또는 ATK 를 봐야 한다 → `kw_dyn(k, cost, atk)`
       · 배수가 None (연소)                → 체력을 봐야 한다 → `burn_mult(n, hp)`
       그래서 이 함수는 코스트·체력·ATK 를 함께 받는다. 호출부에서 빠뜨리면
       3코 / 체력 1 / ATK 0 기준으로 계산돼 **조용히** 어긋난다.
    ⚠ 카드에 인쇄되는 문구는 표의 설명에서 ' — ' **앞부분만** 쓴다("연소 3").
       규칙 설명은 카드가 아니라 확대창 용어집(GLOSSARY)이 맡는다.
    """
    mult, adj, texts = 1.0, 0, []
    for k in keys:
        if k in KW:
            m, a, t = KW[k]
            mult *= burn_mult(int(k[2:]), hp) if m is None else m
            adj += kw_dyn(k, cost, atk) if a is None else a
            texts.append(t.split(" — ")[0] if " — " in t else t)
        else:
            m = CUSTOM.match(k)
            if not m:
                raise KeyError(f"알 수 없는 키워드: {k}")
            adj += int(m.group(1))
            texts.append(m.group(2))
    return mult, adj, " · ".join(texts) if texts else "—"


def cbase(n):
    return int(B["a"] * n + B["b"] + (n - 1) ** 2 * B["k"] + 0.5)


def color_req(c):
    return min(3, max(1, math.ceil((c - 1) / 2)))


