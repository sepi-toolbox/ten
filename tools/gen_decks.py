GROW_MULT = 1.5

# 연소 배수 — **몇 턴을 쓸 수 있느냐**로 매긴다. 수명 = ceil(체력 / 연소 N).
# 8턴 안에 끝나는 게임이라 6턴 이상 사는 크리처에게는 사실상 디메리트가 없다.
# ⚠ 체력은 카드에 적힌 **입력값**이라 순환 참조가 없다(검산은 그대로 한 번에 끝난다).
#   반대로 스탯을 예산에 맞춰 **채워 넣을 때는** 체력이 배수를 바꾸므로 후보를 훑어야 한다.
BURN_LIFE = {1: 1.70, 2: 1.45, 3: 1.28, 4: 1.16, 5: 1.08}
BURN_LONG = 1.03


def burn_mult(n, hp):
    return BURN_LIFE.get(math.ceil(hp / n) if n else 99, BURN_LONG)


def kw_dyn(key, cost, atk=0):
    """가감이 **카드 자신의 수치에 달린** 키워드. (KW 의 가감이 None 인 것들)

    밀물 — 되돌릴 수 있는 상한이 곧 자기 코스트라 값도 코스트를 따라간다.
    성장 N — N턴 뒤 예산이 ×1.5 로 뛴다. 이득 0.5·cbase 를 기다린 턴 수로 나눈다.
    흡혈 — 한 번 때릴 때 ATK/2 만큼 회복한다. HP 1 ≈ 예산 0.5 이고 평균 2회쯤 꽂히므로
           총 회복 ≈ ATK HP ≈ 예산 0.5·ATK → **−ceil(ATK/2)**. 폭발(−ATK)의 절반이다.
    폭발 — 터질 때 얼굴에 ATK 만큼 들어간다. 얼굴 피해 1 ≈ 예산 1 이므로 그대로 −ATK.
    """
    cb = cbase(cost)
    if key == "폭발":
        return -atk
    if key == "흡혈":
        return -((atk + 1) // 2)
    if key == "속공":
        return -round(cb * 0.35)
    if key == "환류":
        # 한 번 더 쓰는 값 ≈ 제 예산의 35%. 전액이 아닌 것은 한 턴 늦고 마나를 다시 내기 때문이다.
        return -max(1, round(cb * 0.35))
    if key == "밀물":
        return -(1 + cost)
    if key.startswith("성장"):
        n = int(key[2:])
        return -max(1, round(cb * (GROW_MULT - 1) / n))
    raise KeyError(f"코스트 의존 키워드가 아니다: {key}")


