# 검산에서 통째로 빠지는 이름 전부. 라벨은 갈라 찍는다(왜 빠졌는지가 서로 다르다).
NOBUDGET = FOEONLY | LANDBORN

#   물 — 시작 덱은 **커먼만** 싣는데 승인 목록에 5·6코 커먼이 하나도 없다
#        (스킬라 레어 · 폭풍의 정령 언커먼 · 크라켄 레어). 그래서 5·6코를 통째로 비우고
#        그 6장을 1~4코로 몰아 준 빠른 커브를 쓴다. 고코스트 몸은 원정 보상으로만 얻는다.
CURVE_OVERRIDE = {"fire":  {1: 3, 2: 5, 3: 6, 4: 5, 5: 2, 6: 1, 8: 1},
                  "water": {1: 4, 2: 7, 3: 7, 4: 5}}


def check_creature(cost, tag, atk, hp, keys, name=None):
    """희귀도 배수는 **키워드 배수 다음에, 가감 전에** 곱한다.
    (가감은 '대가 6' 처럼 절대량으로 사는 것이라 희귀도로 부풀리면 이중 할인이 된다.)"""
    aw, hw, tadj = W[tag]
    mult, adj, text = kw_resolve(keys, cost, hp, atk)
    spent = aw * atk + hw * hp
    bud = round((cbase(cost) + tadj) * mult * rmult(name)) + adj
    return spent, bud, spent - bud, text


def check_spell(kind, val, ref, adj, name=None):
    """⚠ 기준값은 **정수로 반올림**한다.

    스펠의 수치는 정수 하나뿐이라 7.7 같은 기준을 맞출 방법이 없다. 소수로 두면
    언커먼·레어 스펠 12종이 상시 '여유 -0.7' 로 잡히는데, 이건 여유가 아니라
    **맞출 수 없는 눈금**이다. 정수로 반올림해 놓으면 '올릴 수 있는데 안 올렸다' 가
    분명히 드러나고, 크리처처럼 채워 넣을 수 있다.
    """
    if kind in ("요격", "바운스"):
        return val, "—", 0
    r = int((ref + adj) * rmult(name) + 0.5)
    return val, r, val - r


# 인챈트 범위 배수 — 한 번 발동으로 **몇 개체를 건드리는가**.
#   전체     3.5  판이 꽉 찼을 때의 평균 개체 수
#   조건전체 2.0  '내 연소 크리처 전부' 처럼 **부분집합**만 받는 것(불의 샘)
#   단일     1.0
SCOPE = {"전체": 3.5, "조건전체": 2.0, "단일": 1.0}


def check_enchant(cost, drain, E, C, scope, name=None):
    sc = SCOPE.get(scope, 1.0)
    eff = E * C * sc
    tgt = round(CT[cost] * DRAIN_MULT[drain] * rmult(name))
    return eff, tgt, eff - tgt


def fmt(x):
    return f"{x:g}" if isinstance(x, float) else str(x)


def main():
    total_over = 0
    rows_out = []
    for el, deck in DECKS.items():
        name_m, core, flow, note = MECH[el]
        print("=" * 86)
        print(f"[{KO[el]}] {name_m}")
        print(f"  핵심 · {core}")
        print(f"  흐름 · {flow}")
        print(f"  비용 · {note}")
        print("-" * 86)
        n_cards, over = 0, 0
        curve = {}

        def tally(cost, cp):
            nonlocal n_cards
            n_cards += cp
            curve[cost] = curve.get(cost, 0) + cp

        print("  ▸ 크리처 11종")
        for (nm, c, tag, a, h, cp, keys) in deck["creatures"]:
            sp, bd, dv, text = check_creature(c, tag, a, h, keys, nm)
            v = "적 전용" if nm in FOEONLY else ("지형산물" if nm in LANDBORN else (
                "적정" if dv == 0 else (f"초과+{dv}" if dv > 0 else f"여유{dv}")))
            if dv > 0 and nm not in NOBUDGET:
                over += 1
            cap = " ⚠ATK캡" if tag in ("수호", "비행수호") and a > c - 1 and c > 1 else ""
            tally(c, cp)
            print(f"    {nm:<12}{c}코 {tag:<5}{a:>2}/{h:<2} ×{cp}  {sp:>3}/{bd:<3} {v:<7}{text}{cap}")
            rows_out.append(dict(element=el, kind="creature", name=nm, cost=c, tag=tag,
                                 atk=a, hp=h, copies=cp, rule=text, cost_color=color_req(c),
                                 cost_generic=c - color_req(c), budget=bd, spent=sp, verdict=v))

        print("  ▸ 스펠 7종")
        for (nm, c, kind, val, ref, adj, cp, rule) in deck["spells"]:
            vv, rr, dv = check_spell(kind, val, ref, adj, nm)
            v = "적 전용" if nm in FOEONLY else ("지형산물" if nm in LANDBORN else (
                "적정" if dv == 0 else (f"초과+{fmt(dv)}" if dv > 0 else f"여유{fmt(dv)}")))
            if dv > 0 and nm not in NOBUDGET:
                over += 1
            tally(c, cp)
            print(f"    {nm:<12}{c}코 {kind:<5}{fmt(val):>4}  ×{cp}  기준{fmt(rr):<5}{v:<7}{rule}")
            rows_out.append(dict(element=el, kind="spell", name=nm, cost=c, tag=kind,
                                 atk="", hp="", copies=cp, rule=rule, cost_color=color_req(c),
                                 cost_generic=c - color_req(c), budget=rr, spent=vv, verdict=v))

        print("  ▸ 인챈트 2종")
        for (nm, c, dr, E, C, scope, cp, rule) in deck["enchants"]:
            eff, tgt, dv = check_enchant(c, dr, E, C, scope, nm)
            v = "적 전용" if nm in FOEONLY else ("지형산물" if nm in LANDBORN else (
                "적정" if abs(dv) <= 2 else (f"초과+{dv:.0f}" if dv > 0 else f"여유{dv:.0f}")))
            if dv > 2 and nm not in NOBUDGET:
                over += 1
            tally(c, cp)
            print(f"    {nm:<12}{c}코 {dr:<4} E{E}×C{C} ×{cp}  {eff:>4.0f}/{tgt:<4}{v:<7}{rule}")
            rows_out.append(dict(element=el, kind="enchant", name=nm, cost=c, tag=dr,
                                 atk=E, hp=C, copies=cp, rule=rule, cost_color=color_req(c),
                                 cost_generic=c - color_req(c), budget=tgt, spent=eff, verdict=v))

        # 매수 0 = **카드 풀에만 있고 덱에는 안 실린 카드**. 종수·장수·커브 검산에서 빠진다.
        kinds = sum(1 for k in ("creatures", "spells", "enchants")
                    for row in deck[k] if row[5 if k == "creatures" else 6] > 0)
        pool_only = [row[0] for k in ("creatures", "spells", "enchants")
                     for row in deck[k] if row[5 if k == "creatures" else 6] == 0]
        cv = " · ".join(f"{k}코 {v}" for k, v in sorted(curve.items()) if v)
        tgt_cv = CURVE_OVERRIDE.get(el, TARGET_CURVE)
        miss = [f"{k}코 {curve.get(k,0)}≠{tgt_cv.get(k,0)}"
                for k in sorted(set(list(tgt_cv) + list(curve)))
                if curve.get(k, 0) != tgt_cv.get(k, 0)]
        print("-" * 86)
        print(f"  종류 {kinds}종 · 카드 {n_cards}장 + 지형 17 = {n_cards+17}장"
              + (f"   (덱 미수록 {len(pool_only)}종: {', '.join(pool_only)})" if pool_only else ""))
        print(f"  커브 {cv}   {'✓ 목표 일치' if not miss else '✗ ' + ', '.join(miss)}")
        if kinds != 20 or n_cards != 23 or miss:
            over += 1
        print(f"  예산 초과 {over}건\n")
        total_over += over

    if "--check" not in sys.argv:
        path = os.path.join(DATA, "sample_decks.csv")
        with open(path, "w", newline="", encoding="utf-8-sig") as f:
            w = csv.DictWriter(f, fieldnames=["element", "kind", "name", "cost", "cost_color",
                                              "cost_generic", "tag", "atk", "hp", "copies",
                                              "rule", "budget", "spent", "verdict"])
            w.writeheader()
            for r in rows_out:
                w.writerow(r)
        print(f"→ data/sample_decks.csv 작성 ({len(rows_out)}행)")

    print("=" * 86)
    print(f"총 문제 {total_over}건 · 카드 {len(rows_out)}종")
    if total_over:
        sys.exit(1)
    print("✅ 7덱 × 20종 전원 예산 이내 · 커브 일치")


if __name__ == "__main__":
    main()
