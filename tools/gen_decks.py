TARGET_CURVE = {1: 3, 2: 5, 3: 5, 4: 4, 5: 4, 6: 2}


def check_creature(cost, tag, atk, hp, keys):
    aw, hw, tadj = W[tag]
    mult, adj, text = kw_resolve(keys)
    spent = aw * atk + hw * hp
    bud = round((cbase(cost) + tadj) * mult) + adj
    return spent, bud, spent - bud, text


def check_spell(kind, val, ref, adj):
    if kind in ("요격", "바운스"):
        return val, "—", 0
    r = ref + adj
    return val, r, val - r


def check_enchant(cost, drain, E, C, scope):
    sc = 3.5 if scope == "전체" else 1.0
    eff = E * C * sc
    tgt = round(CT[cost] * DRAIN_MULT[drain])
    return eff, tgt, eff - tgt


def fmt(x):
    return f"{x:g}" if isinstance(x, float) else str(x)


def main():
    total_over = 0
    rows_out = []
    for el, deck in DECKS.items():
        name_m, core, flow, note = MECH[el]
        print("=" * 86)
        print(f"[{KO[el]}] {name_m}")
        print(f"  핵심 · {core}")
        print(f"  흐름 · {flow}")
        print(f"  비용 · {note}")
        print("-" * 86)
        n_cards, over = 0, 0
        curve = {}

        def tally(cost, cp):
            nonlocal n_cards
            n_cards += cp
            curve[cost] = curve.get(cost, 0) + cp

        print("  ▸ 크리처 11종")
        for (nm, c, tag, a, h, cp, keys) in deck["creatures"]:
            sp, bd, dv, text = check_creature(c, tag, a, h, keys)
            v = "적정" if dv == 0 else (f"초과+{dv}" if dv > 0 else f"여유{dv}")
            if dv > 0:
                over += 1
            cap = " ⚠ATK캡" if tag in ("수호", "비행수호") and a > c - 1 and c > 1 else ""
            tally(c, cp)
            print(f"    {nm:<12}{c}코 {tag:<5}{a:>2}/{h:<2} ×{cp}  {sp:>3}/{bd:<3} {v:<7}{text}{cap}")
            rows_out.append(dict(element=el, kind="creature", name=nm, cost=c, tag=tag,
                                 atk=a, hp=h, copies=cp, rule=text, cost_color=color_req(c),
                                 cost_generic=c - color_req(c), budget=bd, spent=sp, verdict=v))

        print("  ▸ 스펠 7종")
        for (nm, c, kind, val, ref, adj, cp, rule) in deck["spells"]:
            vv, rr, dv = check_spell(kind, val, ref, adj)
            v = "적정" if dv == 0 else (f"초과+{fmt(dv)}" if dv > 0 else f"여유{fmt(dv)}")
            if dv > 0:
                over += 1
            tally(c, cp)
            print(f"    {nm:<12}{c}코 {kind:<5}{fmt(val):>4}  ×{cp}  기준{fmt(rr):<5}{v:<7}{rule}")
            rows_out.append(dict(element=el, kind="spell", name=nm, cost=c, tag=kind,
                                 atk="", hp="", copies=cp, rule=rule, cost_color=color_req(c),
                                 cost_generic=c - color_req(c), budget=rr, spent=vv, verdict=v))

        print("  ▸ 인챈트 2종")
        for (nm, c, dr, E, C, scope, cp, rule) in deck["enchants"]:
            eff, tgt, dv = check_enchant(c, dr, E, C, scope)
            v = "적정" if abs(dv) <= 2 else (f"초과+{dv:.0f}" if dv > 0 else f"여유{dv:.0f}")
            if dv > 2:
                over += 1
            tally(c, cp)
            print(f"    {nm:<12}{c}코 {dr:<4} E{E}×C{C} ×{cp}  {eff:>4.0f}/{tgt:<4}{v:<7}{rule}")
            rows_out.append(dict(element=el, kind="enchant", name=nm, cost=c, tag=dr,
                                 atk=E, hp=C, copies=cp, rule=rule, cost_color=color_req(c),
                                 cost_generic=c - color_req(c), budget=tgt, spent=eff, verdict=v))

        kinds = sum(len(deck[k]) for k in ("creatures", "spells", "enchants"))
        cv = " · ".join(f"{k}코 {curve.get(k,0)}" for k in range(1, 7))
        miss = [f"{k}코 {curve.get(k,0)}≠{TARGET_CURVE[k]}" for k in range(1, 7)
                if curve.get(k, 0) != TARGET_CURVE[k]]
        print("-" * 86)
        print(f"  종류 {kinds}종 · 카드 {n_cards}장 + 지형 17 = {n_cards+17}장")
        print(f"  커브 {cv}   {'✓ 목표 일치' if not miss else '✗ ' + ', '.join(miss)}")
        if kinds != 20 or n_cards != 23 or miss:
            over += 1
        print(f"  예산 초과 {over}건\n")
        total_over += over

    if "--check" not in sys.argv:
        path = os.path.join(DATA, "sample_decks.csv")
        with open(path, "w", newline="", encoding="utf-8-sig") as f:
            w = csv.DictWriter(f, fieldnames=["element", "kind", "name", "cost", "cost_color",
                                              "cost_generic", "tag", "atk", "hp", "copies",
                                              "rule", "budget", "spent", "verdict"])
            w.writeheader()
            for r in rows_out:
                w.writerow(r)
        print(f"→ data/sample_decks.csv 작성 ({len(rows_out)}행)")

    print("=" * 86)
    print(f"총 문제 {total_over}건 · 카드 {len(rows_out)}종")
    if total_over:
        sys.exit(1)
    print("✅ 7덱 × 20종 전원 예산 이내 · 커브 일치")


if __name__ == "__main__":
    main()
